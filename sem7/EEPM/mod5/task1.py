import numpy as np

np.set_printoptions(precision=4, suppress=True)

# вихідні дані (млн. грн.)
x11, x12, y1 = 1120, 950, 1970      # розподіл випуску промисловості
x21, x22, y2 = 850, 720, 1250       # розподіл випуску сільського господарства
x1 = x11 + x12 + y1                 # повний випуск промисловості
x2 = x21 + x22 + y2                 # повний випуск сільського господарства
print("Повний випуск минулого року: x1 =", x1, " x2 =", x2)

# матриця прямих витрат A, a_ij = x_ij / x_j
A = np.array([[x11 / x1, x12 / x2],
              [x21 / x1, x22 / x2]])
E = np.eye(2)
print("\nМатриця прямих витрат A:\n", A)

# продуктивність: λ_A < 1  <=>  матриця продуктивна
lam = np.linalg.eigvals(A)
print("\nВласні числа A:", lam, " число Фробеніуса =", max(lam.real))
print("Матриця продуктивна:", max(abs(lam)) < 1)

# матриця повних витрат B = (E - A)^(-1)
B = np.linalg.inv(E - A)
print("\nМатриця повних витрат B = (E-A)^-1:\n", B)

# модель Леонтьєва: x = B c
c = np.array([2150, 1530])          # новий кінцевий попит
x = B @ c
print("\nНовий кінцевий попит c =", c)
print("Необхідний повний випуск x = B c =", x)
print("Перевірка: A x + c =", A @ x + c)